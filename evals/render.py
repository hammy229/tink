"""Turn the measured results into docs/results.md and the README chart, so no number is ever typed by hand.

    uv run --group eval python -m evals.render

tests/test_evals.py fails if docs/results.md doesn't match the JSON next to it.
"""
import json
from pathlib import Path

ROOT = Path(__file__).parent.parent
RESULTS = ROOT / "evals" / "results"
DOC = ROOT / "docs" / "results.md"
FIGURE = ROOT / "docs" / "figures" / "accuracy.svg"

NAMES = {
    "dysarthric_other_session": "Dysarthric speech, taught in one sitting, tested on another day",
    "controls_other_session": "Control speakers, taught in one sitting, tested on another day",
    "dysarthric": "Dysarthric speech, any session",
    "controls": "Control speakers, any session",
    "recanvo_one_sitting": "Spontaneous sounds, taught in one sitting, tested on another day",
    "recanvo": "Spontaneous sounds, taught across days, tested on another day",
}
ORDER = list(NAMES)


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def points(x: float) -> str:
    return f"{x * 100:+.1f}"


def ci(r: dict) -> str:
    return f"{pct(r['mean'])} [{r['low'] * 100:.1f}, {r['high'] * 100:.1f}]"


def diff(r: dict) -> str:
    verdict = "better" if r["better"] else "worse" if r["worse"] else "no clear difference"
    return f"{points(r['mean'])} [{r['low'] * 100:+.1f}, {r['high'] * 100:+.1f}], {verdict}"


def _table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


ROUTED = ("dysarthric", "controls", "dysarthric_other_session", "controls_other_session", "recanvo_one_sitting",
          "recanvo")


def _spread(rates: dict) -> str:
    return f"{min(rates.values()) * 100:.0f}% to {max(rates.values()) * 100:.0f}%"


def routing_section(routing: dict) -> list[str]:
    b = routing["benchmarks"]
    budget = f"{routing['budget'] * 100:.0f}%"
    return [
        "## Local first, server when unsure",
        "",
        f"The device runs `{routing['device']}`, the file the browser downloads. The server runs "
        f"{routing['server']}. The device answers when its own confidence is high enough and sends the rest. "
        f"Each person's threshold is the one that kept everyone else in the benchmark within a {budget} budget, so "
        "the person's own sounds never pick it. Generated by `evals/routing.py`.",
        "",
        _table(["Benchmark", "People", "Device only", "Server only", "Routed", "Share of the server's gain",
                "Sounds sent, mean per person", "Sent, per person", "Change against device only",
                "Change against sending as many at random"],
               [[NAMES[k], str(b[k]["people"]), pct(b[k]["budget"]["device"]), pct(b[k]["budget"]["server"]),
                 pct(b[k]["budget"]["accuracy"]["mean"]),
                 "none to gain" if b[k]["budget"]["share_of_server_gain"] is None
                 else f"{b[k]['budget']['share_of_server_gain'] * 100:.0f}%", pct(b[k]["budget"]["fallback"]),
                 _spread(b[k]["budget"]["fallback_per_person"]), diff(b[k]["budget"]["vs_device"]),
                 diff(b[k]["budget"]["vs_random"])] for k in ROUTED]),
        "",
        "Every threshold, on dysarthric speech in any session. A threshold of 0 never sends and 1.01 always does.",
        "",
        _table(["Threshold", "Sounds sent", "Routed", "Same share sent at random"],
               [[k, pct(t["fallback"]), pct(t["accuracy"]["mean"]), pct(t["random"])]
                for k, t in b["dysarthric"]["thresholds"].items()]),
        "",
    ]


def render(report: dict, load: dict, gates: list[dict], routing: dict | None = None) -> str:
    b = report["benchmarks"]
    head = report["head"]
    ad = report["adaptive"]
    un = report["uncertainty"]
    out = [
        "# Results",
        "",
        f"Generated by `evals/render.py` from `evals/results/*.json`, measured at commit `{report['git_sha']}`. "
        "Don't edit this by hand. How these were measured and what they mean: [accuracy.md](accuracy.md).",
        "",
        "Every interval is a 95% bootstrap over people, not clips. Every comparison is paired on identical episodes.",
        "",
        "## Accuracy",
        "",
        _table(["Benchmark", "People", "Accuracy", "Chance", "Questions to the right answer", "Right within 2",
                "Right within 3"],
               [[NAMES[k], str(b[k]["people"]), ci(b[k]["baseline"]), pct(b[k]["baseline"]["chance"]),
                 f"{b[k]['baseline']['mean_questions']:.2f}", pct(b[k]["baseline"]["within_2"]),
                 pct(b[k]["baseline"]["within_3"])] for k in ORDER]),
        "",
        "## Per person",
        "",
        _table(["Benchmark", "Accuracy per person"],
               [[NAMES[k], ", ".join(f"{p} {v * 100:.0f}%" for p, v in b[k]["baseline"]["per_person"].items())]
                for k in ORDER]),
        "",
        "## Which embedding model",
        "",
        "Change against voc2vec (what Tink ships), in points.",
        "",
        _table(["Model", *[NAMES[k] for k in ("recanvo", "dysarthric_other_session", "dysarthric")]],
               [[m, *[f"{pct(b[k]['models'][m]['mean'])} ({diff(b[k]['models'][m]['vs_baseline'])})"
                      for k in ("recanvo", "dysarthric_other_session", "dysarthric")]]
                for m in ("logmel", "hubert", "wav2vec2")]),
        "",
        "## Which scoring method",
        "",
        _table(["Method", *[NAMES[k] for k in ("recanvo", "dysarthric_other_session", "dysarthric")]],
               [[m, *[f"{pct(b[k]['methods'][m]['mean'])} ({diff(b[k]['methods'][m]['vs_baseline'])})"
                      for k in ("recanvo", "dysarthric_other_session", "dysarthric")]]
                for m in ("uncentered", "nearest", "lda")]),
        "",
        "## How deep the model needs to be",
        "",
        _table(["Layer", *[NAMES[k] for k in ("recanvo", "dysarthric_other_session", "dysarthric")]],
               [[layer, *[f"{pct(b[k]['layers'][layer]['mean'])} "
                          f"({points(b[k]['layers'][layer]['vs_baseline']['mean'])})"
                          for k in ("recanvo", "dysarthric_other_session", "dysarthric")]]
                for layer in ("0", "3", "6", "9", "11", "12")]),
        "",
        "## Candidates held to the promotion gate",
        "",
        "Each must beat what ships, on spontaneous and on deliberate sounds, with the paired interval above zero and "
        "p < 0.05 on an exact sign-flip test. The head's gate was set before it ran. The learning experiment reused "
        "that bar afterward and was redesigned after a review on these same benchmarks, so treat it as exploratory.",
        "",
        _table(["Candidate", "Spontaneous", "Deliberate", "Gate", "Decision"], [
            ["Prototypical-network head, trained leave one person out", diff(head["recanvo"]["vs_baseline"]),
             diff(head["dysarthric"]["vs_baseline"]), "passed" if head["passes_gate"] else "failed",
             "Shipped" if head["passes_gate"] else "Not shipped"],
            ["Learning from confirmed sounds", diff(ad["recanvo"]["vs_static"]),
             diff(ad["all_torgo_other_session"]["vs_static"]), "passed" if ad["passes_gate"] else "failed",
             "Shipped" if ad["passes_gate"] else "Not shipped"],
        ]),
        "",
        "## Is augmenting each take worth it",
        "",
        "The app enrolls each take plus 4 variants, which is 5 times the model calls. Every other table here is "
        "without augmentation, so this is the comparison that connects them to what the app does.",
        "",
        _table(["Benchmark", "Off", "On", "Change"],
               [[NAMES[k], pct(report["augmentation"][k]["off"]["mean"]), pct(report["augmentation"][k]["on"]["mean"]),
                 diff(report["augmentation"][k]["vs_off"])] for k in ORDER]),
        "",
        "## Can Tink trust its own confidence",
        "",
        _table(["Benchmark", "Calibration error, self-calibrated", "Calibration error, fixed temperature",
                "Accuracy when answering the surest 25%", "Conformal coverage (target 90%)", "Mean set size"],
               [[NAMES[k], pct(un[k]["ece_self_calibrated"]), pct(un[k]["ece_fixed_temp"]),
                 pct(un[k]["risk_coverage"]["0.25"]), pct(un[k]["conformal_coverage"]),
                 f"{un[k]['conformal_mean_set']:.1f} of {un[k]['ways']:.1f}"] for k in ORDER]),
        "",
        "## Leakage check",
        "",
        "Shuffled labels should score at chance. If they scored higher, the evaluation itself would be leaking.",
        "",
        _table(["Benchmark", "Shuffled accuracy", "Chance"],
               [[NAMES[k], pct(v["accuracy"]), pct(v["chance"])] for k, v in report["leakage_check"].items()]),
        "",
        "This only proves the scoring doesn't leak. It can't catch session or mic effects, which survive a shuffle; "
        "the tested-on-another-day benchmarks are what address those.",
        "",
        "## The model that ships",
        "",
        "Re-embedding the benchmarks with the exact exported file, compared with PyTorch on identical episodes.",
        "",
        _table(["File", "Size", "Benchmark", "Exported", "PyTorch", "Change", "Gate"],
               [[g["model"], f"{g['bytes'] / 1e6:.0f} MB", NAMES[r["benchmark"]], pct(r["exported"]), pct(r["pytorch"]),
                 points(r["diff"]["mean"]), "passed" if r["passes"] else "failed"]
                for g in gates for r in g["results"]]),
        "",
        "## One server under load",
        "",
        f"{load['machine']}, {load['clip_seconds']} s clips, {load['sounds']} sounds with "
        f"{load['takes_per_sound']} takes each. {load['note'].capitalize()}. "
        "`/healthz` runs during the load, to show the server stays responsive.",
        "",
        _table(["Clients", "Requests", "Errors", "Requests per second", "p50", "p95", "p99", "/healthz p95"],
               [[str(r["clients"]), str(r["requests"]), str(r["errors"]), f"{r['throughput_rps']:.0f}",
                 f"{r['p50_ms']:.0f} ms", f"{r['p95_ms']:.0f} ms", f"{r['p99_ms']:.0f} ms",
                 f"{r['healthz_p95_ms']:.0f} ms"] for r in load["results"]]),
        "",
    ]
    if routing is not None:
        out += routing_section(routing)
    return "\n".join(out)


README_START, README_END = "<!-- results:start -->", "<!-- results:end -->"


def readme_block(report: dict) -> str:
    b = report["benchmarks"]
    return _table(["Benchmark", "People", "Accuracy", "Chance", "Right within 2 questions"],
                  [[NAMES[k], str(b[k]["people"]), ci(b[k]["baseline"]), pct(b[k]["baseline"]["chance"]),
                    pct(b[k]["baseline"]["within_2"])] for k in ORDER])


def with_readme_block(text: str, report: dict) -> str:
    head, rest = text.split(README_START)
    _, tail = rest.split(README_END)
    return f"{head}{README_START}\n{readme_block(report)}\n{README_END}{tail}"


def figure(report: dict) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    matplotlib.rcParams.update({"svg.hashsalt": "tink", "font.family": "DejaVu Sans", "font.size": 11})
    ink, muted, grid, surface, series = "#0b0b0b", "#52514e", "#e6e5e0", "#fcfcfb", "#2a78d6"
    b = report["benchmarks"]
    rows = list(reversed(ORDER))
    fig, ax = plt.subplots(figsize=(10.5, 4.0), facecolor=surface)
    ax.set_facecolor(surface)
    for i, k in enumerate(rows):
        r = b[k]["baseline"]
        ax.plot([r["low"] * 100, r["high"] * 100], [i, i], color=series, lw=2, solid_capstyle="round", zorder=2)
        ax.plot(r["mean"] * 100, i, "o", color=series, ms=8, mec=surface, mew=2, zorder=3)
        ax.text(r["high"] * 100 + 1.5, i, f"{r['mean'] * 100:.0f}%", va="center", color=ink, fontsize=11)
        ax.plot([r["chance"] * 100] * 2, [i - 0.26, i + 0.26], color=muted, lw=2, solid_capstyle="round", zorder=2)
    top = len(rows) - 1
    ax.annotate("chance", (b[rows[top]]["baseline"]["chance"] * 100, top + 0.26), xytext=(0, 3),
                textcoords="offset points", ha="center", va="bottom", color=muted, fontsize=10)
    ax.set_yticks(range(len(rows)), [f"{NAMES[k]} (n={b[k]['people']})" for k in rows], color=ink, fontsize=10)
    ax.set_xlim(0, 100)
    ax.set_ylim(-0.6, len(rows) - 0.2)
    ax.set_xticks(range(0, 101, 20), [f"{v}%" for v in range(0, 101, 20)], color=muted)
    ax.xaxis.grid(True, color=grid, lw=1)
    ax.set_axisbelow(True)
    ax.tick_params(length=0)
    for spine in ax.spines.values():
        spine.set_visible(False)
    ax.set_title("Accuracy with one person's own examples (mean and 95% CI over people)", loc="left", color=ink,
                 fontsize=12, pad=16, x=-1.0)
    fig.tight_layout()
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURE, facecolor=surface, metadata={"Date": None})


def load_all() -> tuple[dict, dict, list[dict], dict | None]:
    routing = RESULTS / "routing.json"
    return (json.loads((RESULTS / "report.json").read_text()), json.loads((RESULTS / "load.json").read_text()),
            [json.loads(p.read_text()) for p in sorted(RESULTS.glob("gate-*.json"))],
            json.loads(routing.read_text()) if routing.exists() else None)


def main() -> None:
    report, load, gates, routing = load_all()
    DOC.write_text(render(report, load, gates, routing))
    readme = ROOT / "README.md"
    readme.write_text(with_readme_block(readme.read_text(), report))
    figure(report)
    print(f"wrote {DOC} and {FIGURE}")


if __name__ == "__main__":
    main()
